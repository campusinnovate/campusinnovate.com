// Builds a review-only shared-project DEV installer. NEVER executes against Supabase.
import {readFile,writeFile,mkdir} from 'node:fs/promises';
const root=new URL('../',import.meta.url);
const read=p=>readFile(new URL(p,root),'utf8');
const schema=JSON.parse(await read('scripts/finance-pilot-schema-fixture.json'));
const coa=JSON.parse(await read('scripts/finance-pilot-coa-fixture.json'));
const quote=s=>"'"+String(s).replaceAll("'","''")+"'";
const ns='finance_pilot_dev', priv='finance_pilot_dev_private';
const transform=s=>s.replaceAll('finance_pilot_private',priv).replaceAll('public.',ns+'.').replaceAll("'public'",quote(ns)).replaceAll("set search_path=public",'set search_path='+ns)
 .replaceAll('finance-pilot-evidence','finance-pilot-dev-evidence').replaceAll('finance-period:','finance-dev-period:').replaceAll('finance-request:','finance-dev-request:')
 .replace("where m.user_id=auth.uid() and m.status='active';", "where m.user_id=auth.uid() and m.status='active' and m.id=finance_pilot_dev.current_membership_id();")
 .replace(/create policy (finance_pilot_[a-z_]+) on storage\.objects/g,(_,name)=>'create policy '+name.replace('finance_pilot_','finance_pilot_dev_')+' on storage.objects');
const migrations=['20260930110000_finance_pilot_accounting_core.sql','20261007060737_finance_pilot_workflows.sql','20261007061234_finance_pilot_reports.sql','20261007062328_finance_pilot_scoped_access.sql'];
const sources=await Promise.all(migrations.map(n=>read('supabase/migrations/'+n)));
let sql=`-- GENERATED by scripts/build-finance-pilot-shared-dev.mjs; REVIEW BEFORE APPLY.
-- SHARED PROJECT DEV ONLY. Does not apply the production finance migrations.
-- Project ref must be lxwqhtuhlddgwfxjtlas; verify externally before execution.
begin;
set local lock_timeout='3s';
set local statement_timeout='90s';
do $$ begin
 if exists(select 1 from pg_namespace where nspname in ('${ns}','${priv}'))
 or exists(select 1 from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname='public' and p.proname like 'finance_pilot_dev_%')
 or exists(select 1 from storage.buckets where id='finance-pilot-dev-evidence')
 then raise exception 'Shared DEV already exists/collides. Stop and review; do not overwrite.'; end if;
end $$;
create schema ${ns};
create schema ${priv};
revoke all on schema ${ns},${priv} from public,anon,authenticated;
grant usage on schema ${ns},${priv} to authenticated;
create table ${priv}.settings(id boolean primary key default true check(id),enabled boolean not null);
insert into ${priv}.settings values(true,true);
create table ${priv}.participants(user_id uuid primary key,position_key text not null check(position_key in ('coo','ceo')));
-- Minimal explicit test allowlist; no names/emails/profiles copied.
insert into ${priv}.participants(user_id,position_key)
select m.user_id,p.key from public.memberships m join public.positions p on p.id=m.position_id where m.status='active' and p.key in ('coo','ceo') and m.user_id is not null;
alter table ${priv}.settings enable row level security;
alter table ${priv}.participants enable row level security;
`;
for(const t of schema){
 const cols=t.columns.map(c=>{
  const type=c.data_type==='USER-DEFINED'?'text':c.data_type==='ARRAY'?'text[]':c.data_type;
  let def=c.default_value?transform(c.default_value):null;
  if(def&&(/nextval\(|public\./.test(def)))throw new Error('Unsafe fixture default '+t.name+'.'+c.name);
  return `"${c.name}" ${type}${c.options.includes('identity')?' generated always as identity':def?' default '+def:''}${c.options.includes('nullable')?'':' not null'}${c.options.includes('unique')?' unique':''}`;
 });
 sql+=`create table ${t.name.replace('public.',ns+'.')}(${cols.join(',')}${t.primary_keys.length?',primary key('+t.primary_keys.join(',')+')':''});\n`;
}
sql+=`create function ${ns}.current_membership_id() returns uuid language sql stable security definer set search_path='' as $$
 select d.id from ${ns}.memberships d join ${ns}.positions dp on dp.id=d.position_id
 join ${priv}.participants a on a.user_id=d.user_id and a.position_key=dp.key
 join public.memberships live on live.user_id=d.user_id and live.status='active'
 join public.positions lp on lp.id=live.position_id and lp.key=dp.key
 where d.user_id=auth.uid() and d.status='active' and exists(select 1 from ${priv}.settings where enabled) limit 1;
$$;\n`;
sql+=transform(await read('scripts/finance-pilot-auth-fixture.sql')).trim().replace(/;?$/, ';')+'\n';
for(const a of coa)sql+=`insert into ${ns}.finance_coa(code,name,account_class,cash_flow_category,control_position,default_flow) values(${[a.code,a.name,a.account_class,a.cash_flow_category,a.control_position,'Non-Kas'].map(quote).join(',')});\n`;
for(const [i,key] of ['coo','ceo','cto','business_development_staff','project_lead','growth_marketing_staff','finance_staff','viewer'].entries())sql+=`insert into ${ns}.positions(id,key,name) values('00000000-0000-0000-0000-${String(i+1).padStart(12,'0')}',${quote(key)},${quote('DEV '+key)});\n`;
for(const [i,key] of ['finance_manager','executive','system_admin'].entries())sql+=`insert into ${ns}.roles(id,key,name) values('00000000-0000-0000-0000-${String(i+50).padStart(12,'0')}',${quote(key)},${quote('DEV '+key)});\n`;
sql+=`insert into ${ns}.finance_sequences(document_type,prefix,period_key,last_number) values('invoice','DEV-INV','202610',0),('receipt','DEV-RCPT','202610',0),('quotation','DEV-QUO','202610',0),('transaction','DEV-TX','202610',0);\n`;
for(const code of sources)sql+=transform(code)+'\n';
// Revoke all base-table direct access and enable RLS. Financial APIs own their authorization.
sql+=`do $$ declare t record; begin
 for t in select tablename from pg_tables where schemaname='${ns}' loop
 execute format('alter table ${ns}.%I enable row level security',t.tablename);
 execute format('revoke all on table ${ns}.%I from public,anon,authenticated',t.tablename);
 end loop;
end $$;\n`;
sql+=`create function ${priv}.bind_self() returns uuid language plpgsql security definer set search_path='' as $$
declare pk text; pid uuid; mid uuid;
begin
 if auth.uid() is null or not exists(select 1 from ${priv}.settings where enabled) then raise exception 'DEV unavailable.' using errcode='42501'; end if;
 select p.key into pk from public.memberships m join public.positions p on p.id=m.position_id join ${priv}.participants a on a.user_id=m.user_id and a.position_key=p.key where m.user_id=auth.uid() and m.status='active' limit 1;
 if pk is null then raise exception 'User not on DEV participant allowlist.' using errcode='42501'; end if;
 select id into pid from ${ns}.positions where key=pk;
 perform pg_advisory_xact_lock(hashtextextended('finance-dev-bind:'||auth.uid()::text,0));
 select id into mid from ${ns}.memberships where user_id=auth.uid();
 if mid is null then
 insert into ${ns}.memberships(user_id,email,position_id,engagement_type,status) values(auth.uid(),'dev-'||auth.uid()::text||'@test.invalid',pid,'employee','active') returning id into mid;
 elsif not exists(select 1 from ${ns}.memberships where id=mid and position_id=pid and status='active') then
 update ${ns}.memberships set position_id=pid,status='active' where id=mid;
 end if;
 return mid;
end $$;
revoke all on function ${priv}.bind_self() from public,anon,authenticated;
create function public.finance_pilot_dev_bind() returns uuid language sql security definer set search_path='' as $$ select ${priv}.bind_self(); $$;
revoke all on function public.finance_pilot_dev_bind() from public,anon;
grant execute on function public.finance_pilot_dev_bind() to authenticated;
`;
const signatures=new Map();
for(const source of sources){
 for(const match of source.matchAll(/create\s+or\s+replace\s+function\s+public\.(finance_(?:pilot|next)_[a-z_]+)\s*\(([\s\S]*?)\)\s*returns\s+(uuid|jsonb|text|void|boolean)\b/gi))signatures.set(match[1],{args:match[2],type:match[3]});
}
for(const [name,{args,type}] of signatures){
 const wrapper=name.startsWith('finance_pilot_')?name.replace('finance_pilot_','finance_pilot_dev_'):name.replace('finance_next_','finance_pilot_dev_next_');
 const params=[...args.matchAll(/\b(p_[a-z_]+)\s+(?:uuid|text|date|numeric|boolean|jsonb)\b/g)].map(m=>m[1]);
 if(args.trim()&&params.length===0)throw new Error('Unparsed signature '+name);
 sql+=`create function public.${wrapper}(${args}) returns ${type} language sql security invoker set search_path='' as $$ select ${ns}.${name}(${params.join(',')}); $$;\n`;
 const types=params.map(p=>args.match(new RegExp('\\b'+p+'\\s+(uuid|text|date|numeric|boolean|jsonb)\\b'))[1]).join(',');
 sql+=`revoke all on function public.${wrapper}(${types}) from public,anon;\ngrant execute on function public.${wrapper}(${types}) to authenticated;\n`;
}
// Storage policy subqueries run as caller: keep membership tables private and use a guarded helper.
sql+=`create function ${priv}.can_upload() returns boolean language sql stable security definer set search_path='' as $$
select exists(select 1 from ${ns}.memberships m join ${ns}.positions p on p.id=m.position_id where m.id=${ns}.current_membership_id() and p.key='coo') and ${ns}.current_user_has_permission('finance_next.manage');
$$;
revoke all on function ${priv}.can_upload() from public,anon;
grant execute on function ${priv}.can_upload() to authenticated;
alter policy finance_pilot_dev_evidence_upload on storage.objects with check(bucket_id='finance-pilot-dev-evidence' and (storage.foldername(name))[1]=auth.uid()::text and ${priv}.can_upload());
`;
// Existing broad Storage policies must not bypass isolation for this one new bucket.
sql+=`create policy finance_pilot_dev_storage_read_guard on storage.objects as restrictive for select to authenticated using(bucket_id<>'finance-pilot-dev-evidence' or (${ns}.current_membership_id() is not null and ((storage.foldername(name))[1]=auth.uid()::text or ${priv}.can_view())));
create policy finance_pilot_dev_storage_insert_guard on storage.objects as restrictive for insert to authenticated with check(bucket_id<>'finance-pilot-dev-evidence' or (${ns}.current_membership_id() is not null and (storage.foldername(name))[1]=auth.uid()::text));
create policy finance_pilot_dev_storage_update_guard on storage.objects as restrictive for update to authenticated using(bucket_id<>'finance-pilot-dev-evidence') with check(bucket_id<>'finance-pilot-dev-evidence');
create policy finance_pilot_dev_storage_delete_guard on storage.objects as restrictive for delete to authenticated using(bucket_id<>'finance-pilot-dev-evidence');
revoke all on function ${ns}.current_user_has_permission(text) from public,anon,authenticated;
revoke all on function ${ns}.current_membership_id() from public,anon;
grant execute on function ${ns}.current_membership_id() to authenticated;
revoke all on all tables in schema ${priv} from public,anon,authenticated;
commit;\n`;
await mkdir(new URL('supabase/dev/finance-pilot/',root),{recursive:true});
await writeFile(new URL('supabase/dev/finance-pilot/install.sql',root),sql);
await writeFile(new URL('supabase/dev/finance-pilot/disable.sql',root),`-- Review-only recovery: preserve DEV data, revoke endpoints and Storage through the enabled flag.\nbegin;\nupdate ${priv}.settings set enabled=false;\ndo $$ declare f record; begin\n for f in select p.oid::regprocedure sig from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname='public' and p.proname like 'finance_pilot_dev_%' loop\n execute format('revoke all on function %s from public,anon,authenticated',f.sig);\n end loop;\nend $$;\ncommit;\n`);
console.log(JSON.stringify({output:'supabase/dev/finance-pilot/install.sql',wrappers:signatures.size+1,productionExecuted:false}));
